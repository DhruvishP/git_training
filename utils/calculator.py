def add_nums(a, b):
    """Adds two numbers together."""
    return a + b

def divide_nums(a, b):
    """Divides two numbers."""
    return a / b

def subtract_nums(a, b):
    """Subtracts the second number from the first."""
    return a - b

def power_nums(a, b):
    """Raises the first number to the power of the second."""
    return a ** b

def multiply_nums(a, b):
    """Multiplies two numbers."""
    return a * b
